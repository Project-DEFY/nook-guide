// Flat lookup: sectionId → { section, part }
export function findSection(id) {
  for (const part of GUIDE_STRUCTURE.parts) {
    const section = part.sections.find(s => s.id === id);
    if (section) return { section, part };
  }
  return null;
}

// All sections flat (for search index)
export function allSections() {
  return GUIDE_STRUCTURE.parts.flatMap(part =>
    part.sections.map(s => ({ ...s, part }))
  );
}
